#!/usr/bin/env node
import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const [major,minor]=process.versions.node.split('.').map(Number);
if(major<24||(major===24&&minor<9))throw Error('Node.js >=24.9.0 required');
const root=fileURLToPath(new URL('../',import.meta.url));
const target=resolve(root,'cordis.patch.yml');
const path=fileURLToPath(new URL('../src/index.mjs',import.meta.url));
const content=`# Generated by npm run setup. No existing DSH configuration is edited.\n- insert:\n    - id: r3-graph\n      name: ${JSON.stringify(path)}\n`;
try {const old=await readFile(target,'utf8');if(old!==content)throw Error('cordis.patch.yml already exists with different content; move it first.');}
catch(e){if(e.code!=='ENOENT')throw e;await writeFile(target,content,{flag:'wx'});}
console.log(`Created ${target}\nRun: dsh web --patch ${JSON.stringify(target)}\nFor a DSH source checkout: pnpm dsh web --patch ${JSON.stringify(target)}`);
